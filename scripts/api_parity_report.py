def usage_mark(o: Op, client: str) -> str:
    us = o.users.get(client)
    if not us:
        return ""
    return "Y" if any(u.method for u in us) else "?"


def build_report(ops, stale, dead, unresolved, present: dict, generated_at: str) -> str:
    L = []
    active = [c for c in CLIENTS if present.get(c.key)]
    labels = {c.key: c.label for c in CLIENTS}
    L.append(BEGIN_MARKER)
    L.append("")
    L.append(f"_Generated {generated_at} by `scripts/api_parity_report.py` - do not edit by hand "
             "(everything between the GENERATED markers is overwritten on each run)._")
    L.append("")
    L.append("Scanned: " + "; ".join(
        f"**{labels[k]}** `{v}`" if v else f"**{labels[k]}** (skipped: not found)"
        for k, v in present.items() if v is not None))
    L.append("")

    # ---- headline
    used_any = [o for o in ops if o.users]
    L.append("## Headline")
    L.append("")
    L.append(f"- Endpoints in contract: **{len(ops)}** (method + path)")
    for c in active:
        n = sum(1 for o in ops if o.users.get(c.key))
        L.append(f"- Used by {c.label}: **{n}**")
    unused = [o for o in ops if not o.users and o.audience != "infra"]
    L.append(f"- Used by no client (excl. infra): **{len(unused)}**")
    L.append(f"- Client calls with no matching endpoint/method (stale): **{len(stale)}**")
    L.append(f"- Helper calls whose path could not be resolved statically: **{len(unresolved)}**")
    L.append(f"- API references in dead files (imported by nothing; not counted as usage): **{len(dead)}**")
    L.append("")

    # ---- gaps
    gaps = compute_gaps(ops, present)
    L.append("## Gaps (expected-audience heuristic)")
    L.append("")
    L.append("Audience: admin -> admin panel; rm -> web; vendor -> web + partner app; "
             "customer/public -> web + customer app; mobile -> both apps; shared (any logged-in role) and infra -> no expectation.")
    L.append("")
    for title, items in gaps.items():
        L.append(f"### {title} ({len(items)})")
        L.append("")
        if title.startswith("Vendor/RM/admin endpoints still referenced in the customer app"):
            n_dead = sum(1 for d in dead if d["client"] == "customer")
            if n_dead:
                L.append(f"_Plus {n_dead} reference(s) in dead customer-app files - see "
                         "\"API references in dead files\" below._")
                L.append("")
        if not items:
            L.append("_none_")
            L.append("")
            continue
        L.append("| Endpoint | Feature | Role | Used by |")
        L.append("|---|---|---|---|")
        for o in sorted(items, key=lambda o: (o.tag, o.path, o.method)):
            L.append(f"| `{o.method.upper()} {o.path}` | {o.tag} | {fmt_role(o)} | {fmt_users(o, active)} |")
        L.append("")

    # ---- stale
    L.append("## Stale client calls (no matching backend endpoint)")
    L.append("")
    if stale:
        L.append("| Client | Call | Problem | Where |")
        L.append("|---|---|---|---|")
        for s in sorted(stale, key=lambda s: (s["client"], s["raw"])):
            L.append(f"| {labels[s['client']]} | `{s['method'] or '?'} {s['raw']}` | {s['kind']} | "
                     f"`{s['file']}:{s['line']}` |")
    else:
        L.append("_none_")
    L.append("")

    # ---- dead files
    L.append("## API references in dead files")
    L.append("")
    L.append("These files are imported by no other source file and are not framework entry "
             "points, so their calls are NOT counted above. Delete the file, or wire it up.")
    L.append("")
    if dead:
        L.append("| Client | Call | Where |")
        L.append("|---|---|---|")
        for s in sorted(dead, key=lambda s: (s["client"], s["file"], s["line"])):
            L.append(f"| {labels[s['client']]} | `{s['method'] or '?'} {s['raw']}` | `{s['file']}:{s['line']}` |")
    else:
        L.append("_none_")
    L.append("")

    # ---- per-feature summary
    L.append("## Coverage by feature (OpenAPI tag)")
    L.append("")
    L.append("Counts are endpoints in the tag used by each client.")
    L.append("")
    L.append("| Feature | Endpoints | " + " | ".join(c.label for c in active) + " | Unused |")
    L.append("|---|---:|" + "---:|" * len(active) + "---:|")
    tags = sorted({o.tag for o in ops})
    for t in tags:
        tops = [o for o in ops if o.tag == t]
        row = [t, str(len(tops))]
        for c in active:
            row.append(str(sum(1 for o in tops if o.users.get(c.key))))
        row.append(str(sum(1 for o in tops if not o.users)))
        L.append("| " + " | ".join(row) + " |")
    L.append("")

    # ---- full matrix
    L.append("## Endpoint matrix")
    L.append("")
    L.append("`Y` = called with a matching method; `?` = path referenced but method not "
             "determinable statically. Role is inferred from the router's dependencies.")
    L.append("")
    for t in tags:
        L.append(f"### {t}")
        L.append("")
        L.append("| Endpoint | Role | Audience | " + " | ".join(c.label for c in active) + " |")
        L.append("|---|---|---|" + "---|" * len(active))
        for o in sorted((o for o in ops if o.tag == t), key=lambda o: (o.path, o.method)):
            marks = [usage_mark(o, c.key) for c in active]
            L.append(f"| `{o.method.upper()} {o.path}` | {fmt_role(o)} | {o.audience} | " + " | ".join(marks) + " |")
        L.append("")

    # ---- unresolved
    L.append("## Unresolved dynamic calls")
    L.append("")
    L.append("Helper calls whose path argument is not a literal/template/file-local const. "
             "Check these by hand; they may hide real usages.")
    L.append("")
    if unresolved:
        L.append("| Client | Where | Argument |")
        L.append("|---|---|---|")
        for u in unresolved:
            expr = " ".join(u["expr"].split()).replace("|", "\\|")
            L.append(f"| {labels[u['client']]} | `{u['file']}:{u['line']}` | `{expr}` |")
    else:
        L.append("_none_")
    L.append("")
    L.append(END_MARKER)
    return "\n".join(L) + "\n"


def fmt_role(o: Op) -> str:
    return o.role + (f" ({o.role_detail})" if o.role_detail else "")


def fmt_users(o: Op, active) -> str:
    return ", ".join(c.label for c in active if o.users.get(c.key)) or "-"


def compute_gaps(ops, present) -> dict:
    has = lambda k: bool(present.get(k))  # noqa: E731
    U = lambda o, k: bool(o.users.get(k))  # noqa: E731
    g = {}
    if has("customer") and has("web"):
        g["Customer app behind web (customer/public endpoint used by web, not by customer app)"] = [
            o for o in ops if o.audience in ("customer", "public") and U(o, "web") and not U(o, "customer")]
        g["Web behind customer app (customer/public endpoint used by customer app, not by web)"] = [
            o for o in ops if o.audience in ("customer", "public") and U(o, "customer") and not U(o, "web")]
    if has("partner") and has("web"):
        g["Partner app behind web (vendor endpoint used by web, not by partner app)"] = [
            o for o in ops if o.audience == "vendor" and U(o, "web") and not U(o, "partner")]
        g["Web behind partner app (vendor endpoint used by partner app, not by web)"] = [
            o for o in ops if o.audience == "vendor" and U(o, "partner") and not U(o, "web")]
    if has("customer"):
        g["Vendor/RM/admin endpoints still referenced in the customer app (should be gone after the vendor split)"] = [
            o for o in ops if o.audience in ("vendor", "rm", "admin") and U(o, "customer")]
    if has("partner"):
        g["Customer/RM/admin endpoints referenced in the partner app"] = [
            o for o in ops if o.audience in ("customer", "rm", "admin") and U(o, "partner")]
    if has("admin"):
        g["Admin endpoints not used by the admin panel"] = [
            o for o in ops if o.audience == "admin" and not U(o, "admin")]
        g["Admin endpoints called from non-admin clients"] = [
            o for o in ops if o.audience == "admin" and any(U(o, k) for k in ("web", "customer", "partner"))]
    g["Endpoints used by no client (excl. infra)"] = [
        o for o in ops if not o.users and o.audience != "infra"]
    return g


DEFAULT_HEADER = "# API parity report\n\n(Hand-written notes go above the generated section.)\n\n"


def write_doc(out: Path, generated: str) -> None:
    if out.exists():
        text = out.read_text(encoding="utf-8")
        if BEGIN_MARKER in text:
            head = text.split(BEGIN_MARKER)[0]
            tail = text.split(END_MARKER, 1)[1] if END_MARKER in text else ""
            out.write_text(head + generated + tail.lstrip("\n"), encoding="utf-8")
            return
        out.write_text(text.rstrip("\n") + "\n\n" + generated, encoding="utf-8")
        return
    out.write_text(DEFAULT_HEADER + generated, encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--openapi", default=str(ROOT / "openapi" / "openapi.json"))
    ap.add_argument("--api-src", default=str(ROOT / "app" / "api"),
                    help="router source dir used to infer roles")
    for c in CLIENTS:
        ap.add_argument(f"--{c.key}", default=str(PROJECTS / c.default_dir) if c.default_dir else "",
                        help=f"{c.label} repo (default: ../{c.default_dir or '<skipped>'}; '' to skip)")
    ap.add_argument("--out", default=str(ROOT / "docs" / "API_PARITY.md"))
    ap.add_argument("--json", help="also write raw results to this JSON file")
    ap.add_argument("--stdout", action="store_true", help="print the generated section, write nothing")
    a = ap.parse_args(argv)

    ops = load_ops(Path(a.openapi))
    if Path(a.api_src).is_dir():
        infer_roles(ops, Path(a.api_src))
    top_segs = {o.segs[0] for o in ops if o.segs}

    present: dict[str, str] = {}
    all_usages, all_unresolved = [], []
    for c in CLIENTS:
        repo = Path(getattr(a, c.key)) if getattr(a, c.key) else None
        if not repo or not repo.is_dir():
            present[c.key] = "" if repo else None  # None = not requested (hidden)
            print(f"[skip] {c.label}: " + (f"{repo} not found" if repo else "not requested"),
                  file=sys.stderr)
            continue
        present[c.key] = repo.name
        us, un = scan_client(repo, c, top_segs)
        print(f"[scan] {c.label}: {len(us)} path usages, {len(un)} unresolved", file=sys.stderr)
        all_usages += us
        all_unresolved += un

    stale, dead = attribute(ops, all_usages)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    report = build_report(ops, stale, dead, all_unresolved, present, generated_at)

    if a.stdout:
        sys.stdout.reconfigure(encoding="utf-8")
        print(report)
    else:
        write_doc(Path(a.out), report)
        print(f"[ok] wrote {a.out}", file=sys.stderr)
    if a.json:
        data = {
            "generated_at": generated_at,
            "clients": present,
            "endpoints": [{
                "method": o.method.upper(), "path": o.full_path, "tag": o.tag,
                "role": o.role, "role_detail": o.role_detail, "audience": o.audience,
                "source": o.source,
                "used_by": {k: sorted({f"{u.file}:{u.line}" for u in v}) for k, v in o.users.items()},
            } for o in ops],
            "stale_calls": stale,
            "dead_file_calls": dead,
            "unresolved_calls": all_unresolved,
        }
        Path(a.json).write_text(json.dumps(data, indent=2), encoding="utf-8")
        print(f"[ok] wrote {a.json}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
