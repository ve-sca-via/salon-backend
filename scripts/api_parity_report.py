def _audience(o: Op) -> str:
    """Which client family *should* call this endpoint (heuristic)."""
    if o.role in ("admin", "internal"):
        return "admin"
    if o.role in ("rm", "vendor", "customer"):
        return o.role
    for prefix in sorted(PATH_AUDIENCE, key=len, reverse=True):
        if o.path.startswith(prefix):
            return PATH_AUDIENCE[prefix]
    first = o.segs[0] if o.segs else ""
    if first in PREFIX_AUDIENCE:
        return PREFIX_AUDIENCE[first]
    if "admin" in o.segs:
        return "admin"
    # In-body user_role checks are shown in the Role column but NOT used for the
    # audience: they are as often branches ("admins also see inactive rows") as gates.
    if o.role == "authenticated":
        return "shared"
    if first in ("health", "") or o.full_path in ("/", "/health"):
        return "infra"
    if first in ("webhooks",):
        return "infra"
    return "public"


