def match_path(raw: str, ops_by_path: dict) -> list[str]:
    """Return the OpenAPI paths (no prefix) best matching a client path."""
    segs = norm_segs(raw)
    best, best_score = [], -1
    for p, psegs in ops_by_path.items():
        if len(psegs) != len(segs):
            continue
        score, ok = 0, True
        for c, s in zip(segs, psegs):
            sp = s.startswith("{")
            if c == "{*}":
                score += 2 if sp else 0   # prefer param slots, allow literal fallback
            elif sp:
                score += 1                # literal value in a param slot
            elif c == s:
                score += 3
            else:
                ok = False
                break
        if not ok:
            continue
        if score > best_score:
            best, best_score = [p], score
        elif score == best_score:
            best.append(p)
    return best


def attribute(ops: list[Op], usages: list[Usage]):
    by_path: dict[str, list[Op]] = {}
    for o in ops:
        by_path.setdefault(o.path.rstrip("/") or "/", []).append(o)
    ops_by_path = {p: norm_segs(p) for p in by_path}
    stale, dead = [], []
    for u in usages:
        paths = match_path(u.raw, ops_by_path)
        if u.orphan:
            dead.append({"endpoint_paths": paths, **u.__dict__})
            continue
        if not paths:
            stale.append({"kind": "no such path", **u.__dict__})
            continue
        cand_ops = [o for p in paths for o in by_path[p]]
        if u.method:
            hit = [o for o in cand_ops if o.method.upper() == u.method]
            if not hit:
                stale.append({"kind": "method not on path (has: " +
                              ",".join(sorted({o.method.upper() for o in cand_ops})) + ")",
                              **u.__dict__})
                continue
            for o in hit:
                o.users.setdefault(u.client, []).append(u)
        else:
            for o in cand_ops:
                o.users.setdefault(u.client, []).append(u)
    return stale, dead


