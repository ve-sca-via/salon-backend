INTERP = "\x00"


def _skip_string(src: str, i: int) -> int:
    """i at opening quote; return index after closing quote (or end of line)."""
    q = src[i]
    i += 1
    n = len(src)
    while i < n:
        c = src[i]
        if c == "\\":
            i += 2
            continue
        if c == q:
            return i + 1
        if c == "\n":
            return i  # unterminated (JSX text apostrophe etc.)
        i += 1
    return n


def _skip_template(src: str, i: int) -> int:
    """i at opening backtick; return index after closing backtick."""
    i += 1
    n = len(src)
    while i < n:
        c = src[i]
        if c == "\\":
            i += 2
            continue
        if c == "`":
            return i + 1
        if c == "$" and i + 1 < n and src[i + 1] == "{":
            i = _skip_braces(src, i + 1)
            continue
        i += 1
    return n


def _skip_braces(src: str, i: int) -> int:
    """i at an opening bracket; return index after its match (string/template aware)."""
    pairs = {"{": "}", "(": ")", "[": "]"}
    stack = [pairs[src[i]]]
    i += 1
    n = len(src)
    while i < n and stack:
        c = src[i]
        if c in "'\"":
            i = _skip_string(src, i)
            continue
        if c == "`":
            i = _skip_template(src, i)
            continue
        if c == "/" and i + 1 < n and src[i + 1] in "/*":
            i = _skip_comment(src, i)
            continue
        if c in pairs:
            stack.append(pairs[c])
        elif stack and c == stack[-1]:
            stack.pop()
        i += 1
    return i


def _skip_comment(src: str, i: int) -> int:
    if src[i + 1] == "/":
        j = src.find("\n", i)
        return len(src) if j < 0 else j
    j = src.find("*/", i + 2)
    return len(src) if j < 0 else j + 2


def blank_comments(src: str) -> tuple[str, list[tuple[int, int]]]:
    """Return src with comments replaced by spaces, plus literal spans [(start,end)]."""
    out = list(src)
    spans = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c in "'\"":
            j = _skip_string(src, i)
            spans.append((i, j))
            i = j
        elif c == "`":
            j = _skip_template(src, i)
            spans.append((i, j))
            i = j
        elif c == "/" and i + 1 < n and src[i + 1] in "/*":
            j = _skip_comment(src, i)
            for k in range(i, j):
                if out[k] != "\n":
                    out[k] = " "
            i = j
        else:
            i += 1
    return "".join(out), spans


QUERYISH_RE = re.compile(r"[`'\"]\?|toString\(\)|\b(qs|query|queryString|search|params|searchParams|suffix)\b", re.I)


def eval_template(lit: str, consts: dict) -> list[str]:
    """Evaluate a template literal (with backticks) to path candidate(s)."""
    body = lit[1:-1] if lit.endswith("`") else lit[1:]
    out = [""]
    i, n = 0, len(body)
    while i < n:
        c = body[i]
        if c == "\\" and i + 1 < n:
            out = [o + body[i + 1] for o in out]
            i += 2
            continue
        if c == "$" and i + 1 < n and body[i + 1] == "{":
            j = _skip_braces(body, i + 1)
            expr = body[i + 2: j - 1].strip()
            vals = resolve_ident(expr, consts)
            if vals is not None:
                out = [o + v for o in out for v in vals]
            elif QUERYISH_RE.search(expr):
                out = [o + "?" for o in out]
            else:
                out = [o + INTERP for o in out]
            i = j
            continue
        out = [o + c for o in out]
        i += 1
    return out


IDENT_RE = re.compile(r"^[A-Za-z_$][\w$]*(\.[A-Za-z_$][\w$]*)*$")
INDEX_RE = re.compile(r"^([A-Za-z_$][\w$]*)\[[^\]]+\]$")


def resolve_ident(expr: str, consts: dict) -> list[str] | None:
    expr = expr.strip()
    if expr in consts:
        v = consts[expr]
        return v if isinstance(v, list) else [v]
    m = INDEX_RE.match(expr)
    if m and m.group(1) + "[]" in consts:
        return consts[m.group(1) + "[]"]
    return None


def eval_expr(expr: str, consts: dict) -> list[str] | None:
    """Evaluate a JS expression made of literals/templates/known consts joined by +.
    Returns candidate strings (INTERP marks unknown parts) or None if it contains
    no string at all."""
    expr = expr.strip()
    # strip TS casts / parens
    expr = re.sub(r"\s+as\s+[\w.<>\[\]| ]+$", "", expr)
    while expr.startswith("(") and _skip_braces(expr, 0) == len(expr):
        expr = expr[1:-1].strip()
    parts = []
    i, n, start = 0, len(expr), 0
    while i < n:
        c = expr[i]
        if c in "'\"":
            i = _skip_string(expr, i)
        elif c == "`":
            i = _skip_template(expr, i)
        elif c in "([{":
            i = _skip_braces(expr, i)
        elif c == "+":
            parts.append(expr[start:i].strip())
            i += 1
            start = i
        elif c in "?" and expr[i:i + 2] != "?.":
            return None  # ternary: give up on the whole expression
        else:
            i += 1
    parts.append(expr[start:].strip())
    out = [""]
    saw_string = False
    for p in parts:
        if not p:
            continue
        if p[0] in "'\"" and p[-1] == p[0] and len(p) >= 2:
            out = [o + p[1:-1] for o in out]
            saw_string = True
        elif p[0] == "`":
            vals = eval_template(p, consts)
            out = [o + v for o in out for v in vals]
            saw_string = True
        else:
            vals = resolve_ident(p, consts)
            if vals is not None:
                out = [o + v for o in out for v in vals]
                saw_string = True
            elif QUERYISH_RE.search(p):
                out = [o + "?" for o in out]
            else:
                out = [o + INTERP for o in out]
    return out if saw_string else None


CONST_STR_RE = re.compile(
    r"\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*(?::\s*[^=;\n]+)?=\s*(['\"`])")
CONST_OBJ_RE = re.compile(
    r"\b(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*(?::\s*[^=;\n]+)?=\s*\{")
OBJ_PROP_RE = re.compile(r"([A-Za-z_$][\w$]*|['\"][^'\"]+['\"])\s*:\s*(['\"`])")


def collect_consts(code: str) -> dict:
    """File-local string constants and simple string-valued object maps."""
    consts: dict = {}
    for _ in range(2):  # second pass lets consts reference earlier consts
        for m in CONST_STR_RE.finditer(code):
            name, q = m.group(1), m.group(2)
            s = m.end() - 1
            e = _skip_template(code, s) if q == "`" else _skip_string(code, s)
            vals = eval_expr(code[s:e], consts)
            if vals and len(vals) <= 8:
                consts[name] = vals
        for m in CONST_OBJ_RE.finditer(code):
            name = m.group(1)
            s = m.end() - 1
            e = _skip_braces(code, s)
            body = code[s + 1: e - 1]
            allvals = []
            depth_ok = body.count("{") == 0
            if not depth_ok:
                continue
            for pm in OBJ_PROP_RE.finditer(body):
                key = pm.group(1).strip("'\"")
                qs = pm.end() - 1
                qe = _skip_template(body, qs) if pm.group(2) == "`" else _skip_string(body, qs)
                vals = eval_expr(body[qs:qe], consts)
                if vals:
                    consts[f"{name}.{key}"] = vals
                    allvals += vals
            if allvals:
                consts[name + "[]"] = allvals
    return consts


