def _split_args(code: str, open_paren: int) -> list[str]:
    """Top-level argument texts of a call whose '(' is at open_paren."""
    end = _skip_braces(code, open_paren)
    inner = code[open_paren + 1: end - 1]
    args, i, start, n = [], 0, 0, len(inner)
    while i < n:
        c = inner[i]
        if c in "'\"":
            i = _skip_string(inner, i)
        elif c == "`":
            i = _skip_template(inner, i)
        elif c in "([{":
            i = _skip_braces(inner, i)
        elif c == ",":
            args.append(inner[start:i])
            i += 1
            start = i
        else:
            i += 1
    args.append(inner[start:])
    return [a.strip() for a in args]


def to_api_path(candidate: str, client: ClientDef, loose_ok: bool, top_segs: set[str]) -> str | None:
    """Turn an evaluated client string into a normalised backend path (no prefix)."""
    s = candidate
    for marker in (API_PREFIX + "/", "/api/backend/"):
        k = s.find(marker)
        if k >= 0:
            s = s[k + len(marker) - 1:]
            break
    else:
        if not (loose_ok and s.startswith("/")):
            return None
        first = s.strip("/").split("/")[0].split("?")[0]
        if first not in top_segs:
            return None
    s = s.split("?")[0].split("#")[0]
    if not s.startswith("/") or " " in s or len(s) > 200 or "[" in s:
        return None  # "[" = a Next route pattern like /api/backend/[...path], not a call
    segs = norm_segs(s)
    out = []
    for idx, seg in enumerate(segs):
        if seg == INTERP or (INTERP in seg and seg.replace(INTERP, "") == ""):
            out.append("{*}")
        elif INTERP in seg:
            head = seg.split(INTERP)[0]
            # "/salons${suffix}" on the last segment: a glued-on suffix, keep the head.
            if idx == len(segs) - 1 and head and seg.endswith(INTERP) and seg.count(INTERP) == 1:
                out.append(head)
            else:
                out.append("{*}")
        else:
            out.append(seg)
    if not out:
        return None
    return "/" + "/".join(out)


def iter_source_files(repo: Path, client: ClientDef):
    for sd in client.src_dirs:
        base = repo / sd
        if base.is_file():
            yield base
            continue
        if not base.is_dir():
            continue
        for f in base.rglob("*"):
            if f.suffix not in SOURCE_EXTS or not f.is_file():
                continue
            rel_parts = f.relative_to(repo).parts
            if any(p in SKIP_DIR_NAMES for p in rel_parts[:-1]):
                continue
            if SKIP_FILE_RE.search(f.name):
                continue
            yield f


IMPORT_RE = re.compile(r"(?:\bfrom\s+|\bimport\s*\(\s*|\brequire\s*\(\s*|^\s*import\s+)['\"]([^'\"]+)['\"]", re.M)
ENTRY_RE = re.compile(
    r"(^|/)(App|main|index|proxy|middleware|_layout)\.[cm]?[jt]sx?$"
    r"|(^|/)app/.*(^|/)(page|layout|route|loading|error|not-found|template|default|"
    r"global-error|sitemap|robots|manifest|opengraph-image)\.[jt]sx?$")


def imported_stems(files: list[Path]) -> dict[Path, set[str]]:
    """Per file: the last path segment of every module it imports."""
    out = {}
    for f in files:
        try:
            text = f.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        out[f] = {re.sub(r"\.[cm]?[jt]sx?$", "", spec.rstrip("/").split("/")[-1])
                  for spec in IMPORT_RE.findall(text)}
    return out


def is_orphan(f: Path, repo: Path, imports: dict[Path, set[str]]) -> bool:
    """True when no other source file imports this one (by module name) and it is
    not a framework entry point. Name-based, so it errs towards 'imported'."""
    rel = f.relative_to(repo).as_posix()
    if ENTRY_RE.search(rel):
        return False
    stem = re.sub(r"\.[cm]?[jt]sx?$", "", f.name)
    names = {stem, f.parent.name} if stem == "index" else {stem}
    return not any(names & stems for other, stems in imports.items() if other != f)


def scan_client(repo: Path, client: ClientDef, top_segs: set[str]) -> tuple[list[Usage], list[dict]]:
    usages: list[Usage] = []
    unresolved: list[dict] = []
    api_dirs = [repo / d for d in client.api_dirs]
    files = list(iter_source_files(repo, client))
    imports = imported_stems(files)
    for f in files:
        try:
            src = f.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if GENERATED_HEADER_RE.search(src[:500]):
            continue
        code, spans = blank_comments(src)
        consts = collect_consts(code)
        rel = f.relative_to(repo).as_posix()
        orphan = is_orphan(f, repo, imports)
        in_api_dir = any(d == f.parent or d in f.parents for d in api_dirs)
        consumed: list[tuple[int, int]] = []
        resolved_in_calls: set[str] = set()

        def line_of(pos: int) -> int:
            return code.count("\n", 0, pos) + 1

        def emit(cands, method, via, pos, loose):
            got = False
            for cand in cands:
                p = to_api_path(cand, client, loose, top_segs)
                if p:
                    usages.append(Usage(client.key, rel, line_of(pos), method, p, via, orphan))
                    got = True
            return got

        # 1) helper calls
        for m in CALL_RE.finditer(code):
            # skip matches inside string literals
            if any(s <= m.start() < e for s, e in spans):
                continue
            paren = m.end() - 1
            args = _split_args(code, paren)
            if not args or not args[0]:
                continue
            first = args[0]
            fn, verb, obj = m.group("fn"), m.group("verb"), m.group("obj")
            if fn:
                method = HELPER_METHODS[fn]
            elif verb == "request":
                method = None
            else:
                method = verb.upper()
            if method is None:
                opts = " ".join(args[1:])
                mm = METHOD_OPT_RE.search(opts)
                if mm:
                    method = mm.group(1).upper()
                elif fn in ("apiFetch", "fetch") and (len(args) < 2 or "method" not in opts):
                    method = "GET"
            # obj.get(...) on things that are clearly not HTTP clients
            if obj and obj in ("searchParams", "params", "headers", "map", "Map", "cache",
                               "formData", "localStorage", "url", "URL", "cookies", "store"):
                continue
            cands = eval_expr(first, consts)
            arg_start = code.find(first, paren)
            if cands is None:
                if fn in ("apiGet", "apiPost", "apiPut", "apiPatch", "apiDelete", "apiFetch",
                          "multipartUpload") or (obj == "api" and client.key == "web"):
                    if not first.startswith("path") and fn != "fetch":
                        unresolved.append({"client": client.key, "file": rel,
                                           "line": line_of(m.start()), "expr": first[:120]})
                continue
            loose = client.unprefixed_ok and (obj == "api" or fn == "apiFetch")
            if emit(cands, method, "call", m.start(), loose):
                consumed.append((arg_start, arg_start + len(first)))
                resolved_in_calls.update(cands)

        # 2) `url: ...` properties (RTK Query / axios config objects)
        for m in URL_PROP_RE.finditer(code):
            if any(s <= m.start() < e for s, e in spans):
                continue
            vs = m.end()
            # value expression runs to the next top-level , or } or )
            i, n = vs, len(code)
            while i < n and code[i] not in ",}\n)":
                c = code[i]
                if c in "'\"":
                    i = _skip_string(code, i)
                elif c == "`":
                    i = _skip_template(code, i)
                elif c in "([{":
                    i = _skip_braces(code, i)
                else:
                    i += 1
            expr = code[vs:i]
            cands = eval_expr(expr, consts)
            if not cands:
                continue
            # enclosing object: back to the unmatched '{', forward to its match
            depth, j = 0, m.start()
            while j > 0:
                j -= 1
                if code[j] == "}":
                    depth += 1
                elif code[j] == "{":
                    if depth == 0:
                        break
                    depth -= 1
            obj_end = _skip_braces(code, j) if code[j] == "{" else i + 300
            mm = METHOD_OPT_RE.search(code[j:obj_end])
            method = mm.group(1).upper() if mm else "GET"  # axios / axiosBaseQuery default
            if emit(cands, method, "url-prop", m.start(), False):
                consumed.append((vs, i))
                resolved_in_calls.update(cands)

        # 3) any remaining literal that is clearly an API path
        for s, e in spans:
            if any(cs <= s < ce for cs, ce in consumed):
                continue
            lit = src[s:e]
            if lit[0] == "`":
                cands = eval_template(lit, consts)
            else:
                cands = [lit[1:-1]]
            if not any(API_PREFIX + "/" in c or "/api/backend/" in c for c in cands) and not in_api_dir:
                continue
            # Type-level reference to the generated contract, e.g.
            # ApiRequestBody<'/api/v1/auth/me', 'put'> - not a call.
            if TYPE_REF_RE.match(code, e) or re.search(r"\b(?:paths|ApiPath)\s*\[\s*$", code[max(0, s - 20):s]):
                continue
            # A const/map value the file already passes to a helper call
            # (e.g. CART_PATH[kind]) is counted at the call site, with its method.
            if all(c in resolved_in_calls for c in cands):
                continue
            # Element of an array literal (e.g. a NO_AUTH_PATHS list in an api
            # client) - routing metadata, not a call.
            prev = code[:s].rstrip()[-1:]
            nxt = code[e:].lstrip()[:1]
            if prev in ("[", ",") and nxt in (",", "]"):
                continue
            emit(cands, None, "literal", s, client.unprefixed_ok and in_api_dir)
    return usages, unresolved


