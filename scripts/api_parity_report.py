@dataclass
class Op:
    method: str
    path: str            # without /api/v1
    full_path: str
    segs: list[str]
    tag: str
    operation_id: str
    summary: str
    role: str = "?"
    role_detail: str = ""
    source: str = ""
    audience: str = "?"
    users: dict = field(default_factory=dict)  # client -> list[Usage]

    @property
    def key(self) -> str:
        return f"{self.method.upper()} {self.full_path}"


def strip_prefix(p: str) -> str:
    return p[len(API_PREFIX):] or "/" if p.startswith(API_PREFIX + "/") or p == API_PREFIX else p


def norm_segs(p: str) -> list[str]:
    return [s for s in p.strip("/").split("/") if s]


def load_ops(openapi_path: Path) -> list[Op]:
    spec = json.loads(openapi_path.read_text(encoding="utf-8"))
    ops = []
    for full, item in spec["paths"].items():
        for m in HTTP_METHODS:
            if m not in item:
                continue
            o = item[m]
            p = strip_prefix(full)
            ops.append(Op(
                method=m, path=p, full_path=full, segs=norm_segs(p),
                tag=(o.get("tags") or ["untagged"])[0],
                operation_id=o.get("operationId", ""), summary=o.get("summary", ""),
            ))
    return ops


ROLE_DEPS = {
    "require_admin": "admin",
    "require_internal": "internal",
    "require_rm": "rm",
    "require_vendor": "vendor",
    "require_customer": "customer",
    "get_current_user": "authenticated",
    "get_current_user_id": "authenticated",
    "get_optional_user": "public (optional auth)",
}
ROLE_RANK = ["internal", "admin", "rm", "vendor", "customer", "authenticated",
             "public (optional auth)"]


def _call_name(node) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _deps_from_expr(node, aliases: dict) -> set[str]:
    """Role names reachable from a Depends(...) / RequireFeature(...) expression."""
    out: set[str] = set()
    if node is None:
        return out
    for sub in ast.walk(node):
        if isinstance(sub, ast.Call) and _call_name(sub.func) == "Depends" and sub.args:
            out |= _resolve_dep(sub.args[0], aliases)
    return out


def _resolve_dep(target, aliases: dict) -> set[str]:
    if isinstance(target, ast.Call) and _call_name(target.func) == "RequireFeature":
        role_dep = next((k.value for k in target.keywords if k.arg == "role_dependency"), None)
        roles = _resolve_dep(role_dep, aliases) if role_dep is not None else {"admin"}
        return roles | {"feature-gated"}
    if isinstance(target, ast.Call) and _call_name(target.func) == "RoleChecker" and target.args:
        try:
            return set(ast.literal_eval(target.args[0]))
        except Exception:
            return {"authenticated"}
    name = _call_name(target)
    if name in aliases:
        return _resolve_dep(aliases[name], aliases)
    if name in ROLE_DEPS:
        return {ROLE_DEPS[name]}
    return set()


ROLE_CHECK_RE = re.compile(r"user_role\s*(?:==|!=|not in|in)\s*(\[[^\]]*\]|\([^)]*\)|[\"'][a-z_]+[\"'])")


def _router_deps(tree, aliases) -> set[str]:
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) \
                and _call_name(node.value.func) == "APIRouter":
            for kw in node.value.keywords:
                if kw.arg == "dependencies":
                    return _deps_from_expr(kw.value, aliases)
    return set()


def infer_roles(ops: list[Op], api_dir: Path) -> None:
    by_opid = {o.operation_id: o for o in ops}
    pkg_deps: dict[Path, set[str]] = {}
    files = sorted(api_dir.rglob("*.py"))
    trees = {}
    for f in files:
        try:
            src = f.read_text(encoding="utf-8")
            trees[f] = (src, ast.parse(src))
        except (SyntaxError, UnicodeDecodeError):
            continue
    # Package-level router dependencies (e.g. admin/__init__.py -> require_admin).
    for f, (src, tree) in trees.items():
        if f.name == "__init__.py":
            aliases = _module_aliases(tree)
            pkg_deps[f.parent] = _router_deps(tree, aliases)

    for f, (src, tree) in trees.items():
        aliases = _module_aliases(tree)
        file_deps = _router_deps(tree, aliases)
        for parent, deps in pkg_deps.items():
            if f.parent == parent or parent in f.parents:
                file_deps = file_deps | deps
        lines = src.splitlines()
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for dec in node.decorator_list:
                if not (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)
                        and dec.func.attr in HTTP_METHODS and dec.args
                        and isinstance(dec.args[0], ast.Constant)):
                    continue
                method = dec.func.attr
                deps = set(file_deps)
                for kw in dec.keywords:
                    if kw.arg == "dependencies":
                        deps |= _deps_from_expr(kw.value, aliases)
                for d in node.args.defaults + node.args.kw_defaults:
                    deps |= _deps_from_expr(d, aliases)
                body = "\n".join(lines[node.lineno - 1: (node.end_lineno or node.lineno)])
                inbody = set()
                for m in ROLE_CHECK_RE.finditer(body):
                    inbody |= set(re.findall(r"[\"']([a-z_]+)[\"']", m.group(1)))
                # Match to the OpenAPI operation via FastAPI's operationId scheme:
                # re.sub(r"\W", "_", name + full_path) + "_" + method
                # An explicit operation_id= wins; else FastAPI's default scheme.
                explicit = next((k.value.value for k in dec.keywords if k.arg == "operation_id"
                                 and isinstance(k.value, ast.Constant)), None)
                for o in ops:
                    if o.method != method:
                        continue
                    if explicit is not None:
                        hit = o.operation_id == explicit
                    else:
                        hit = re.sub(r"\W", "_", node.name + o.full_path) + "_" + method == o.operation_id
                    if hit:
                        _assign_role(o, deps, inbody, f"{f.relative_to(api_dir.parent.parent).as_posix()}:{node.lineno}")
    for o in ops:
        if o.role == "?" and o.full_path in ("/", "/health"):
            o.role = "public"
        o.audience = _audience(o)


def _module_aliases(tree) -> dict:
    aliases = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 \
                and isinstance(node.targets[0], ast.Name) and isinstance(node.value, ast.Call):
            aliases[node.targets[0].id] = node.value
    return aliases


def _assign_role(o: Op, deps: set[str], inbody: set[str], source: str) -> None:
    gated = "feature-gated" in deps
    deps = deps - {"feature-gated"}
    ranked = [r for r in ROLE_RANK if r in deps] + sorted(d for d in deps if d not in ROLE_RANK)
    o.role = ranked[0] if ranked else "public"
    details = []
    if gated:
        details.append("feature-gated")
    if inbody and o.role in ("authenticated", "public (optional auth)", "public"):
        details.append("in-body check: " + "/".join(sorted(inbody)))
    o.role_detail = ", ".join(details)
    o.source = source


