"""
API parity report: which clients call which backend endpoints.

Loads the committed OpenAPI contract (openapi/openapi.json), infers each
endpoint's required role from the router source (app/api/**), statically scans
every client repo for API path usages, matches them against the contract, and
writes docs/API_PARITY.md (only the generated section; the hand-written part
above the BEGIN marker is preserved).

Stdlib only, Python 3.11+. Read-only on every client repo.

Usage (from backend/):
    python scripts/api_parity_report.py                  # write docs/API_PARITY.md
    python scripts/api_parity_report.py --json out.json  # also dump raw data
    python scripts/api_parity_report.py --stdout         # print instead of writing
    python scripts/api_parity_report.py --web ../salon_management_next --admin "" ...
        (pass an empty string to skip a client)

Refresh the contract first if routes changed:
    .venv/Scripts/python.exe scripts/export_openapi.py
"""

