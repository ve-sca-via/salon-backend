"""
Build the cross-repo docs hub and keep every doc's "Related" footer in sync.

Every Lubist doc starts with a small YAML header (see docs/DOCS_HUB.md → "The doc
header"). This script reads those headers across all sibling repos and:

  1. validates them (required keys, allowed values, `related` targets exist);
  2. regenerates the section of docs/DOCS_HUB.md between the GENERATED markers —
     a status board, a Mermaid map and a table per area;
  3. rewrites the footer of every doc between the RELATED markers with real
     relative links: "Related" (from its own header) and "Referenced by"
     (computed). Those links are what draw the edges in Foam's / Obsidian's graph.

Stdlib only. Run from backend/:

    python scripts/build_docs_hub.py           # write
    python scripts/build_docs_hub.py --check   # exit 1 if anything is stale or invalid
"""
from __future__ import annotations

import argparse
import io
import os
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
ROOT = BACKEND.parent  # g:\vescavia\Projects
REPOS = [
    "backend",
    "salon_management_next",
    "lubist_mobile_application",
    "lubist_vendor_application",
    "salon-admin-panel",
]
HUB = BACKEND / "docs" / "DOCS_HUB.md"
HUB_ID = "backend/docs/DOCS_HUB.md"

SKIP_DIRS = {"node_modules", ".git", ".venv", "venv", ".next", ".expo", "dist", "build",
             "__pycache__", ".pytest_cache", "reports", "supabase", "coverage", ".vercel"}
# Agent-instruction files, not docs.
SKIP_FILES = {"CLAUDE.md", "AGENTS.md"}

AREAS = {
    "cross-cutting": "Cross-cutting (all apps)",
    "backend": "Backend (FastAPI)",
    "web": "Web (Next.js)",
    "mobile": "Customer app (Expo)",
    "partner": "Partner app (Expo)",
    "admin": "Admin panel",
}
TYPES = {"guide", "reference", "runbook", "plan", "tracker", "incident", "generated"}
STATUSES = {
    "current": "✅ current",
    "planned": "🗓️ planned",
    "blocked": "⛔ blocked",
    "open-incident": "🔴 open incident",
    "resolved": "☑️ resolved",
}
REQUIRED = ["title", "area", "type", "status", "updated", "read_when"]

BEGIN_HUB = "<!-- BEGIN GENERATED: build_docs_hub.py -->"
END_HUB = "<!-- END GENERATED: build_docs_hub.py -->"
BEGIN_REL = "<!-- BEGIN RELATED: generated by backend/scripts/build_docs_hub.py from the header's `related:` -->"
END_REL = "<!-- END RELATED -->"
REL_BLOCK_RE = re.compile(re.escape("<!-- BEGIN RELATED:") + r".*?" + re.escape(END_REL), re.S)


@dataclass
class Doc:
    id: str            # workspace-relative, forward slashes: "backend/docs/COUPONS.md"
    path: Path
    meta: dict
    related: list[str] = field(default_factory=list)
    referenced_by: list[str] = field(default_factory=list)


def parse_header(text: str) -> dict | None:
    """Tiny parser for our fixed header shape (scalars, `related:` list, `tags: [..]`)."""
    if not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    if end == -1:
        return None
    meta: dict = {}
    current_list = None
    for raw in text[3:end].splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        if line.lstrip().startswith("- ") and current_list is not None:
            meta[current_list].append(line.strip()[2:].strip())
            continue
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        current_list = None
        if value == "":
            meta[key] = []
            current_list = key
        elif value == "[]":
            meta[key] = []
        elif value.startswith("[") and value.endswith("]"):
            meta[key] = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        else:
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1].replace('\\"', '"')
            meta[key] = value
    return meta


def find_docs() -> tuple[list[Doc], list[str]]:
    docs, unheaded = [], []
    for repo in REPOS:
        base = ROOT / repo
        if not base.is_dir():
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")]
            for name in filenames:
                if not name.lower().endswith(".md") or name in SKIP_FILES:
                    continue
                path = Path(dirpath) / name
                doc_id = path.relative_to(ROOT).as_posix()
                text = io.open(path, encoding="utf-8-sig", newline="").read()
                meta = parse_header(text.replace("\r\n", "\n"))
                if meta is None:
                    unheaded.append(doc_id)
                    continue
                docs.append(Doc(doc_id, path, meta, list(meta.get("related") or [])))
    docs.sort(key=lambda d: d.id)
    return docs, unheaded


def validate(docs: list[Doc]) -> list[str]:
    errors = []
    ids = {d.id for d in docs}
    for d in docs:
        for k in REQUIRED:
            if not d.meta.get(k):
                errors.append(f"{d.id}: missing `{k}`")
        if d.meta.get("area") not in AREAS:
            errors.append(f"{d.id}: area `{d.meta.get('area')}` not in {sorted(AREAS)}")
        if d.meta.get("type") not in TYPES:
            errors.append(f"{d.id}: type `{d.meta.get('type')}` not in {sorted(TYPES)}")
        if d.meta.get("status") not in STATUSES:
            errors.append(f"{d.id}: status `{d.meta.get('status')}` not in {sorted(STATUSES)}")
        for r in d.related:
            if r not in ids:
                errors.append(f"{d.id}: related `{r}` is not a known doc (missing file or header?)")
    return errors


def rel(from_id: str, to_id: str) -> str:
    return Path(os.path.relpath(ROOT / to_id, (ROOT / from_id).parent)).as_posix()


def md_escape(s: str) -> str:
    return s.replace("|", "\\|")


def node_id(doc_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", doc_id)


def build_hub_section(docs: list[Doc]) -> str:
    by_id = {d.id: d for d in docs}
    L: list[str] = [BEGIN_HUB, "", f"_{len(docs)} docs. Regenerate with `python scripts/build_docs_hub.py`._", ""]

    attention = [d for d in docs if d.meta["status"] in ("open-incident", "blocked", "planned")]
    L += ["## Needs attention", ""]
    if attention:
        L += ["| Status | Doc | Read when |", "|---|---|---|"]
        order = ["open-incident", "blocked", "planned"]
        for d in sorted(attention, key=lambda d: order.index(d.meta["status"])):
            L.append(f"| {STATUSES[d.meta['status']]} | [{md_escape(d.meta['title'])}]({rel(HUB_ID, d.id)}) | {md_escape(d.meta['read_when'])} |")
    else:
        L.append("Nothing open.")
    L.append("")

    # Mermaid map — subgraph per area, edges from `related`.
    L += ["## Map", "", "```mermaid", "flowchart LR"]
    for area, label in AREAS.items():
        members = [d for d in docs if d.meta["area"] == area and d.id != HUB_ID]
        if not members:
            continue
        L.append(f'  subgraph {area.replace("-", "_")}["{label}"]')
        for d in members:
            title = d.meta["title"].replace('"', "'")
            L.append(f'    {node_id(d.id)}["{title}"]')
        L.append("  end")
    seen = set()
    for d in docs:
        for r in d.related:
            if r in by_id and d.id != HUB_ID and r != HUB_ID:
                edge = tuple(sorted((d.id, r)))
                if edge not in seen:
                    seen.add(edge)
                    L.append(f"  {node_id(edge[0])} --- {node_id(edge[1])}")
    for d in docs:
        if d.id != HUB_ID:
            L.append(f'  click {node_id(d.id)} "{rel(HUB_ID, d.id)}"')
    L += [
        "  classDef open fill:#fde2e1,stroke:#c0392b,color:#000",
        "  classDef blocked fill:#fdebd0,stroke:#b9770e,color:#000",
        "  classDef planned fill:#e8eaf6,stroke:#5c6bc0,color:#000",
        "  classDef resolved fill:#eeeeee,stroke:#999,color:#555",
    ]
    for status, cls in (("open-incident", "open"), ("blocked", "blocked"), ("planned", "planned"), ("resolved", "resolved")):
        ids = [node_id(d.id) for d in docs if d.meta["status"] == status and d.id != HUB_ID]
        if ids:
            L.append(f"  class {','.join(ids)} {cls}")
    L += ["```", ""]

    for area, label in AREAS.items():
        members = [d for d in docs if d.meta["area"] == area and d.id != HUB_ID]
        if not members:
            continue
        L += [f"## {label}", "", "| Doc | Type | Status | Read when |", "|---|---|---|---|"]
        for d in sorted(members, key=lambda d: (d.meta["type"], d.meta["title"].lower())):
            L.append(
                f"| [{md_escape(d.meta['title'])}]({rel(HUB_ID, d.id)}) | {d.meta['type']} | "
                f"{STATUSES[d.meta['status']]} | {md_escape(d.meta['read_when'])} |"
            )
        L.append("")
    L.append(END_HUB)
    return "\n".join(L)


def build_footer(d: Doc, by_id: dict[str, Doc]) -> str:
    def link(target: str) -> str:
        return f"[{by_id[target].meta['title']}]({rel(d.id, target)})"

    lines = [BEGIN_REL, "", "---", ""]
    if d.related:
        lines.append("**Related:** " + " · ".join(link(r) for r in d.related if r in by_id))
        lines.append("")
    back = [r for r in d.referenced_by if r not in d.related]
    if back:
        lines.append("**Referenced by:** " + " · ".join(link(r) for r in back))
        lines.append("")
    if d.id != HUB_ID:
        lines.append(f"[↑ All docs]({rel(d.id, HUB_ID)})")
        lines.append("")
    lines.append(END_REL)
    return "\n".join(lines)


def apply(path: Path, transform) -> bool:
    """Run transform on LF-normalised text; write back with the file's own newlines. Returns changed?"""
    raw = io.open(path, encoding="utf-8-sig", newline="").read()
    nl = "\r\n" if "\r\n" in raw else "\n"
    text = raw.replace("\r\n", "\n")
    new = transform(text)
    if new == text:
        return False
    io.open(path, "w", encoding="utf-8", newline="").write(new.replace("\n", nl))
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="don't write; exit 1 if anything is stale or invalid")
    args = ap.parse_args()

    docs, unheaded = find_docs()
    by_id = {d.id: d for d in docs}
    for d in docs:
        for r in d.related:
            if r in by_id:
                by_id[r].referenced_by.append(d.id)

    errors = validate(docs)
    for e in errors:
        print(f"ERROR  {e}")
    for u in unheaded:
        print(f"WARN   no header (not in the hub): {u}")

    stale = []

    def hub_transform(text: str) -> str:
        section = build_hub_section(docs)
        if BEGIN_HUB in text:
            head = text.split(BEGIN_HUB)[0]
            tail = text.split(END_HUB, 1)[1] if END_HUB in text else "\n"
            return head + section + tail
        return text.rstrip("\n") + "\n\n" + section + "\n"

    for d in docs:
        footer = build_footer(d, by_id)

        def footer_transform(text: str, footer=footer) -> str:
            if REL_BLOCK_RE.search(text):
                return REL_BLOCK_RE.sub(lambda _: footer, text, count=1)
            return text.rstrip("\n") + "\n\n" + footer + "\n"

        if args.check:
            raw = io.open(d.path, encoding="utf-8-sig", newline="").read().replace("\r\n", "\n")
            if footer_transform(raw) != raw:
                stale.append(d.id)
        else:
            apply(d.path, footer_transform)

    if HUB.exists():
        if args.check:
            raw = io.open(HUB, encoding="utf-8-sig", newline="").read().replace("\r\n", "\n")
            if hub_transform(raw) != raw:
                stale.append(HUB_ID)
        else:
            apply(HUB, hub_transform)  # after footers, so the hub's own footer is current too

    for s in stale:
        print(f"STALE  {s}")
    print(f"{len(docs)} docs, {len(errors)} errors, {len(unheaded)} without a header"
          + (f", {len(stale)} stale" if args.check else ""))
    return 1 if errors or (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
